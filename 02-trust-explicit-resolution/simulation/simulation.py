"""Legacy API delegated to the revised collateral-backed game.

Historical output directories preserve the original model's results. New paper
 evidence is generated by economy_validation with raw episodes, paired seeds,
and an explicit plan; this adapter exists for existing import/CLI callers.
"""
from __future__ import annotations

import random

from .economics import Latents, play
from .legacy_config import to_game
from .types import EpisodeResult, SimConfig, SimResult


def run_episode(config: SimConfig, rng: random.Random) -> EpisodeResult:
    game = to_game(config)
    latent = Latents(tuple(tuple(rng.random() for _ in range(9)) for _ in range(game.participants)), rng.random())
    raw = play(game, latent, keep_actors=True)
    submitted = raw["status"] != "deferred"
    cid = raw["challenger"]
    challenger_payoff = 0.
    if cid is not None:
        actor = raw["actors"][cid]
        position_gain = actor["payout_false"] - actor["payout_true"] if raw["final_wrong"] else 0.
        challenger_payoff = raw["actor_cash_changes"][cid] + position_gain - game.challenger_opportunity_cost
    return EpisodeResult(
        proposal_is_false=raw["proposal_false"], challenged=raw["challenged"], proposal_submitted=submitted,
        adjudicator_correct=not raw["final_wrong"] if raw["challenged"] else True,
        resolution_correct=(not raw["final_wrong"]) if submitted else None,
        eligible_proposers=raw["eligible"], willing_proposers=raw["willing"], num_verifiers=raw["checks"],
        proposer_payoff=raw["proposer_net"], challenger_payoff=challenger_payoff,
        total_bond_locked=raw["bond_locked"], time_to_finalization_hours=raw["latency"],
        bounty_paid=(config.bounty_fraction * game.proposer_bond if raw["challenger_reward"] else 0.),
        attack_attempted=raw["attack_attempted"], terminal_status=raw["status"],
        false_challenge=raw["false_challenge"], wrongful_slash=raw["wrongful_proposer_slash"],
        resource_cost=raw["resource_cost"], opportunity_cost=raw["opportunity_cost"],
        payout_misallocation=raw["payout_misallocation"], balance_error=raw["balance_error"],
        positive_gain_candidates=raw["positive_gain_candidates"],
        positive_gain_truthful=raw["positive_gain_truthful"],
    )


def run_simulation(config: SimConfig) -> SimResult:
    to_game(config)
    rng = random.Random(config.seed)
    return SimResult(config, [run_episode(config, rng) for _ in range(config.num_episodes)])


def run_parameter_sweep(configs: list[SimConfig]) -> list[SimResult]:
    return [run_simulation(c) for c in configs]
